# What is Random Forest Regression?
# Random Forest Regression is a supervised Machine Learning algorithm that combines multiple Decision Trees to predict a continuous numerical value.

# In simple language:

# Instead of depending on one decision tree, it creates multiple decision trees and combines their predictions to produce a final result.


# What is a Decision Tree?
# A Decision Tree is a Machine Learning algorithm that makes predictions using a tree-like structure of conditions and decisions.

# Example:
# - Is distance less than 5 km?
# - If yes, estimate fare using one branch.
# - If no, follow another branch.
# A Random Forest uses many such trees.
# How Random Forest works
# 1. Selects random samples from the training dataset.
# 2. Builds multiple decision trees.
# 3. Each tree predicts a fare.
# 4. Combines the predictions by averaging them.
# 5. Produces the final predicted fare.
# Example
# Suppose three trees predict:
# Decision tree	Predicted fare
# Tree 1	$100
# Tree 2	$110
# Tree 3	$105

# Final prediction:
# \[
# \frac{100+110+105}{3}=105
# \]

# Predicted fare = $105.






# A. R² Score (Coefficient of Determination)
# R² measures how well a regression model explains the variation in the target variable.

# Its maximum value is 1.
# R² value	Interpretation
# 1	Perfect prediction
# Close to 1	Good model fit
# 0	No improvement over predicting the target mean
# Negative	Worse than predicting the target mean

# Higher R² is generally better.
# B. MAE – Mean Absolute Error
# MAE measures the average absolute difference between actual and predicted values.
# \[
# MAE=\frac{1}{n}\sum |y_i-\hat y_i|
# \]

# Example:

# Actual fares: 100, 200, 300

# Predicted fares: 110, 190, 320

# Errors: 10, 10, 20
# \[
# MAE=\frac{10+10+20}{3}
# \]

# \[
# MAE=13.33
# \]

# The average prediction error is $13.33.
# C. MSE – Mean Squared Error
# MSE calculates the average of squared prediction errors.
# \[
# MSE=\frac{1}{n}\sum(y_i-\hat y_i)^2
# \]

# Why square the errors?

# To prevent positive and negative errors from cancelling each other and to penalize larger errors more heavily.

# Lower MSE is better.
# D. RMSE – Root Mean Squared Error
# RMSE is the square root of MSE.
# \[
# RMSE=\sqrt{MSE}
# \]

# It represents the prediction error in the same unit as the target variable.

# Lower RMSE is better.
# Difference between all four metrics
# Metric	Meaning	Better result
# R²	How well the model explains variation	Higher
# MAE	Average absolute error	Lower
# MSE	Average squared error	Lower
# RMSE	Square root of average squared error	Lower


# 3. Important Evaluation Metrics
# Metric	Definition	Better Result
# R² Score	Measures how well the model explains variations in fare.	Higher
# MAE	Average absolute difference between actual and predicted fares.	Lower
# MSE	Average of squared prediction errors.	Lower
# RMSE	Square root of MSE; represents error in the same unit as fare.	Lower

